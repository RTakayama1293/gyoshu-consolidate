def detect_prefecture(address: str) -> str:
    """住所文字列の先頭から都道府県を判定する。

    Args:
        address: 住所文字列（例: "兵庫県相生市..."）。

    Returns:
        判定できた都道府県名。判定不能なら空文字。
    """
    if not address:
        return ""
    addr = address.strip()
    for pref in PREFECTURES:
        if addr.startswith(pref):
            return pref
    return ""


def to_region(pref: str) -> str:
    """都道府県名から地方区分を返す。

    Args:
        pref: 都道府県名。

    Returns:
        地方区分名。未知なら空文字。
    """
    if not pref:
        return ""
    region = PREF_TO_REGION.get(pref, "")
    if OKINAWA_AS_SEPARATE and pref == "沖縄県":
        return "沖縄"
    return region
